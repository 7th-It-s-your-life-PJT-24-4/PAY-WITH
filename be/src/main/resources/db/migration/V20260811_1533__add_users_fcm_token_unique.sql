-- =====================================================================
-- users.fcm_token 유니크 제약
--
-- FCM 토큰은 사용자가 아니라 앱 인스턴스(Firebase 프로젝트 + 브라우저 프로필 +
-- Origin + 푸시 구독)를 가리킨다. 같은 브라우저에서 A 가 로그아웃하지 않은 채
-- B 가 로그인하면 같은 토큰이 반환되므로, 제약이 없으면 한 토큰이 두 사용자 행에
-- 동시에 남을 수 있다. 그 상태에서는 A 의 거래 알림(수취인·금액 포함)이 지금 B 가
-- 쓰는 기기로 간다.
--
-- 애플리케이션에서 등록 시 이전 소유자를 해제하도록 고쳤지만, 두 사용자가 같은
-- 토큰을 동시에 등록하는 경합까지는 앱 로직으로 막을 수 없어 DB 에서 강제한다.
--
-- MySQL 은 유니크 인덱스에서 NULL 중복을 허용하므로 토큰을 등록하지 않은 사용자가
-- 여럿인 것은 그대로 가능하다.
--
-- 부수 효과로 fcm_token 조회에 인덱스가 생긴다. 무효 토큰 정리(clearFcmTokens)와
-- 소유권 이전(clearFcmTokenFromOtherUsers)이 값으로 찾는 쿼리라 지금은 풀스캔이다.
--
-- 지금은 저장된 토큰이 한 건도 없어(프런트 미연동) 무조건 성공한다. 중복이 쌓인
-- 뒤에는 데이터를 먼저 정리해야 하므로 이 시점에 넣어 둔다.
--
-- 나중에 다중 기기를 지원하려고 전용 등록 테이블로 옮기더라도, 유니크는 반드시
-- 토큰 단독이어야 한다. UNIQUE(user_id, token) 로 잡으면 같은 토큰이 서로 다른
-- 사용자에게 각각 등록될 수 있어 위 문제가 그대로 남는다.
-- =====================================================================

ALTER TABLE users
    ADD UNIQUE KEY uk_users_fcm_token (fcm_token);
